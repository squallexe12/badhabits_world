export function localizeCountry(
  locale: "tr" | "en",
  countryCode: string | undefined,
  fallback: string
): string {
  if (!countryCode) return fallback;
  const map = locale === "en" ? COUNTRY_EN : COUNTRY_TR;
  return map[countryCode] ?? fallback;
}
